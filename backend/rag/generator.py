class GeminiProvider(BaseLLMGenerator):
    """Google Gemini API Integration."""
    def __init__(self, api_key: str):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY", "")

    def generate(self, prompt: str, system_prompt: str = "", temperature: float = 0.2) -> str:
        if not self.api_key:
            return "Error: Gemini API key is missing. Please set it in Settings."
        
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={self.api_key}"
        payload = {
            "contents": [
                {"parts": [{"text": f"{system_prompt}\n\n{prompt}"}]}
            ],
            "generationConfig": {
                "temperature": temperature
            }
        }
        try:
            with httpx.Client(timeout=30.0) as client:
                res = client.post(url, json=payload)
                res.raise_for_status()
                data = res.json()
                return data["candidates"][0]["content"]["parts"][0]["text"]
        except Exception as e:
            logger.error(f"Gemini API error: {str(e)}")
            return f"Error connecting to Google Gemini API: {str(e)}"

class OllamaProvider(BaseLLMGenerator):
    """Local Ollama instance integration."""
    def __init__(self, base_url: str = "http://localhost:11434"):
        self.base_url = base_url

    def generate(self, prompt: str, system_prompt: str = "", temperature: float = 0.2) -> str:
        url = f"{self.base_url}/api/generate"
        payload = {
            "model": "llama3",
            "system": system_prompt,
            "prompt": prompt,
            "stream": False,
            "options": {"temperature": temperature}
        }
        try:
            with httpx.Client(timeout=60.0) as client:
                res = client.post(url, json=payload)
                res.raise_for_status()
                return res.json().get("response", "")
        except Exception as e:
            logger.error(f"Ollama error: {str(e)}")
            return f"Could not connect to local Ollama server at {self.base_url}: {str(e)}"

class LLMGenerator:
    """Factory to get configured LLM provider instance."""

    @staticmethod
    def get_generator(provider: str = "mock", api_key: str = "") -> BaseLLMGenerator:
        provider = provider.lower()
        if provider == "openai":
            return OpenAIProvider(api_key=api_key)
        elif provider == "groq":
            return GroqProvider(api_key=api_key)
        elif provider == "gemini":
            return GeminiProvider(api_key=api_key)
        elif provider == "ollama":
            return OllamaProvider()
        else:
            return MockLLMGenerator()
