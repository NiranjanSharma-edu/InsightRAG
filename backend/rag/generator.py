import os
from typing import List, Dict, Any
import httpx
from core.logger import logger

class BaseLLMGenerator:
    """Abstract interface for LLM response generation."""
    def generate(self, prompt: str, system_prompt: str = "", temperature: float = 0.2) -> str:
        raise NotImplementedError

class MockLLMGenerator(BaseLLMGenerator):
    """Built-in offline generator that builds grounded responses without needing external API keys."""

    def generate(self, prompt: str, system_prompt: str = "", temperature: float = 0.2) -> str:
        logger.info("Using MockLLMGenerator (Offline Mode)")
        
        if "Context Passages:" in prompt and "Question:" in prompt:
            try:
                context_part = prompt.split("Context Passages:")[1].split("Question:")[0]
                question_part = prompt.split("Question:")[1].split("Answer:")[0]
                
                answer = f"Based on the provided documents, here is the answer regarding '{question_part.strip()}':\n\n"
                answer += "Key relevant findings extracted from your technical research materials:\n"
                
                lines = [l.strip() for l in context_part.splitlines() if l.strip() and not l.startswith("[Passage") and not l.startswith("-----------------")]
                for line in lines[:3]:
                    if len(line) > 15:
                        answer += f"• {line}\n"
                        
                answer += "\n(Note: This response was generated by InsightRAG's built-in offline engine using retrieved context vector chunks.)"
                return answer
            except Exception:
                pass
                
        return "I am InsightRAG. Upload PDF documents and submit your query to retrieve grounded answers."

class OpenAIProvider(BaseLLMGenerator):
    """OpenAI API Integration."""
    def __init__(self, api_key: str):
        self.api_key = api_key or os.getenv("OPENAI_API_KEY", "")

    def generate(self, prompt: str, system_prompt: str = "", temperature: float = 0.2) -> str:
        if not self.api_key:
            return "Error: OpenAI API key is missing. Please add it in Settings or switch to the Mock provider."
        
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json"
        }
        payload = {
            "model": "gpt-3.5-turbo",
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt}
            ],
            "temperature": temperature
        }
        try:
            with httpx.Client(timeout=30.0) as client:
                res = client.post("https://api.openai.com/v1/chat/completions", json=payload, headers=headers)
                res.raise_for_status()
                data = res.json()
                return data["choices"][0]["message"]["content"]
        except Exception as e:
            logger.error(f"OpenAI generation error: {str(e)}")
            return f"Error connecting to OpenAI: {str(e)}"

